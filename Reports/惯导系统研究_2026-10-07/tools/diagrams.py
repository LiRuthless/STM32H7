from pathlib import Path
from html import escape
ROOT=Path(__file__).resolve().parents[1]
class Diagram:
 def __init__(self,title,subtitle,height=620):
  self.parts=[f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 {height}" role="img" aria-label="{escape(title)}"><title>{escape(title)}</title><defs><marker id="arr" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path d="M0 0L8 4L0 8Z" fill="#416174"/></marker></defs><style>text{{font-family:Microsoft YaHei,Arial,sans-serif}}.title{{font-size:26px;font-weight:bold;fill:#163d52}}.sub{{font-size:17px;fill:#526b79}}.box{{font-size:19px;fill:#183d50}}.note{{font-size:17px;fill:#506873}}.arrow{{fill:none;stroke:#416174;stroke-width:2.5;marker-end:url(#arr)}}</style><rect width="1000" height="{height}" fill="white"/><text class="title" x="500" y="35" text-anchor="middle">{escape(title)}</text><text class="sub" x="500" y="67" text-anchor="middle">{escape(subtitle)}</text>']
 def box(self,x,y,w,h,lines,fill='#eaf3f7'):
  self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="9" fill="{fill}" stroke="#97b6c5"/>')
  start=y+h/2-(len(lines)-1)*13+6
  for i,line in enumerate(lines):self.parts.append(f'<text class="box" x="{x+w/2}" y="{start+i*26}" text-anchor="middle">{escape(line)}</text>')
 def arrow(self,points):self.parts.append('<polyline class="arrow" points="'+' '.join(f'{x},{y}' for x,y in points)+'"/>')
 def note(self,x,y,line):self.parts.append(f'<text class="note" x="{x}" y="{y}" text-anchor="middle">{escape(line)}</text>')
 def save(self,name):
  (ROOT/'figures'/name).write_text(''.join(self.parts)+'</svg>',encoding='utf-8')
